#!/usr/bin/env node
/**
 * mkdocs-to-nextra.mjs
 * 解析 upstream/mkdocs.yml 的 nav：
 *  1) 页面标题：叶子路径 → 显示标题（index.md 对应键为 path/index）
 *  2) 文件夹标题：分组的叶子路径公共目录 → 分组名（如 guide/bones → Bones and Auto-Rig）
 *  3) 遍历 content/docs 文件系统，为每个目录生成 _meta.js（slug 键 → 标题）
 * 中文标题：content/_meta.cn.json（键为相对路径，如 "guide/bones/create-bones"），有则覆盖。
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import YAML from 'yaml'

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const MKDOCS = join(ROOT, 'upstream', 'mkdocs.yml')
const CONTENT = join(ROOT, 'content', 'docs')
const OUT_CN = join(ROOT, 'content', '_meta.cn.json')

if (!existsSync(MKDOCS)) {
  console.error('[nav] upstream/mkdocs.yml not found')
  process.exit(1)
}

const cfg = YAML.parse(readFileSync(MKDOCS, 'utf8'))
const nav = cfg.nav || []

/** 页面标题：relPath（无扩展名）-> 标题；index.md 用 'path/index' */
const pageTitle = new Map()
/** 文件夹标题：relDir -> 标题 */
const folderTitle = new Map()

function pathToKey(mdPath) {
  return mdPath.replace(/\.md$/, '').replace(/^\/+/, '')
}

function collectLeafPaths(items, out = []) {
  for (const item of items) {
    if (typeof item !== 'object' || item === null) continue
    for (const val of Object.values(item)) {
      if (Array.isArray(val)) collectLeafPaths(val, out)
      else if (typeof val === 'string' && !/^https?:/.test(val)) out.push(pathToKey(val))
    }
  }
  return out
}

function commonDir(paths) {
  if (paths.length === 0) return ''
  const segs = paths.map((p) => p.split('/').slice(0, -1))
  let common = segs[0]
  for (const s of segs.slice(1)) {
    let i = 0
    while (i < common.length && i < s.length && common[i] === s[i]) i++
    common = common.slice(0, i)
  }
  return common.join('/')
}

function walkNav(items) {
  for (const item of items) {
    if (typeof item !== 'object' || item === null) continue
    for (const [key, val] of Object.entries(item)) {
      if (Array.isArray(val)) {
        walkNav(val)
        const c = commonDir(collectLeafPaths(val))
        if (c && !folderTitle.has(c)) folderTitle.set(c, key)
      } else if (typeof val === 'string' && !/^https?:/.test(val)) {
        pageTitle.set(pathToKey(val), key)
      }
    }
  }
}
walkNav(nav)

const cn = existsSync(OUT_CN) ? JSON.parse(readFileSync(OUT_CN, 'utf8')) : {}
const pageT = (rel) => cn[rel] || pageTitle.get(rel) || null
const folderT = (rel) => cn[rel] || folderTitle.get(rel) || null

function walkDirs(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) {
      out.push(p)
      walkDirs(p, out)
    }
  }
  return out
}

let metaCount = 0
const dirs = [CONTENT, ...walkDirs(CONTENT)]
for (const dir of dirs) {
  const relDir = dir === CONTENT ? '' : relative(CONTENT, dir).split(sep).join('/')
  const entries = {}
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) {
      const rel = relDir ? `${relDir}/${name}` : name
      const t = folderT(rel)
      if (t) entries[name] = t
    } else if (name.endsWith('.mdx') && !name.startsWith('_')) {
      const slug = name.replace(/\.mdx$/, '')
      const rel = relDir ? `${relDir}/${slug}` : slug
      const t = pageT(rel)
      if (t) entries[slug] = t
    }
  }
  if (Object.keys(entries).length === 0) continue
  writeFileSync(
    join(dir, '_meta.js'),
    '// Generated by scripts/mkdocs-to-nextra.mjs from upstream/mkdocs.yml. Do not edit by hand.\n' +
      'export default ' +
      JSON.stringify(entries, null, 2) +
      '\n',
  )
  metaCount++
}

console.log(`[nav] wrote ${metaCount} _meta.js files under content/docs`)
console.log(
  `[nav] pages: ${pageTitle.size}, folders: ${folderTitle.size}, cn overrides: ${Object.keys(cn).length}`,
)
