#!/usr/bin/env node
/**
 * mkdocs-to-nextra.mjs
 * 解析 upstream/mkdocs.yml 的 nav，生成 content/_meta.js（Nextra 4 结构）。
 * 中文标题由译者在 content/_meta.cn.json 维护（本脚本只做键覆盖提示）。
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import YAML from 'yaml'

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const MKDOCS = join(ROOT, 'upstream', 'mkdocs.yml')
const OUT_META = join(ROOT, 'content', '_meta.js')
const OUT_CN = join(ROOT, 'content', '_meta.cn.json')

if (!existsSync(MKDOCS)) {
  console.error('[nav] upstream/mkdocs.yml not found')
  process.exit(1)
}

const cfg = YAML.parse(readFileSync(MKDOCS, 'utf8'))
const nav = cfg.nav || []

function toRoute(val) {
  // 'guide/bones/index.md' -> '/docs/guide/bones'
  return '/docs/' + val.replace(/\.md$/, '').replace(/\/index$/, '')
}

function convertItems(items) {
  const result = {}
  for (const item of items) {
    if (typeof item === 'string') continue
    for (const [key, val] of Object.entries(item)) {
      if (Array.isArray(val)) {
        result[key] = convertItems(val)
      } else if (typeof val === 'string') {
        if (/^https?:/.test(val)) {
          result[key] = { href: val, newWindow: true }
        } else {
          result[key] = toRoute(val)
        }
      }
    }
  }
  return result
}

const meta = convertItems(nav)
const content =
  '// Generated by scripts/mkdocs-to-nextra.mjs from upstream/mkdocs.yml. Do not edit structure by hand.\n' +
  '// Chinese titles: see _meta.cn.json\n' +
  'export default ' +
  JSON.stringify(meta, null, 2) +
  '\n'
writeFileSync(OUT_META, content)

if (existsSync(OUT_CN)) {
  const cn = JSON.parse(readFileSync(OUT_CN, 'utf8'))
  console.log(`[nav] _meta.cn.json has ${Object.keys(cn).length} zh title keys`)
}
console.log('[nav] wrote content/_meta.js')
